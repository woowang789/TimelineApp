-- V3 — posts 조회 인덱스 후보 A 되돌림 → **후보 B** 적용: (author_id, is_deleted, id DESC)
--
-- 근거: 마스터 §4.1 후보 규정 / 로드맵 20-phase-1-baseline.md P1-13 / M0 분석 docs/perf/m0.md
--
-- 이 파일의 성격 — 되돌림이 곧 기록이다
--   후보 A(V2)를 지우고 후보 B 를 새로 만드는 마이그레이션이다.
--   "A 를 재고, 되돌리고, B 를 쟀다"는 과정이 V2 → V3 이력으로 남는다.
--   결과만 남기고 과정을 지우면 채택 근거도 함께 사라지므로, V2 를 수정하지 않고 V3 를 덧쌓는다.
--   Flyway 를 쓴 이유가 데이터 보호만이 아니라 **인덱스를 추가하고 되돌린 이력이 곧
--   실패한 시도의 기록이 되기 때문**이라는 마스터 §3 의 취지가 이것이다.
--
-- 후보 B 가 A 에 더한 것
--   Pull 쿼리(§4.3)의 조건은 세 개다.
--       WHERE f.follower_id = :userId  AND p.id < :cursor  AND p.is_deleted = false
--       ORDER BY p.id DESC LIMIT 25
--   후보 A 는 author_id 로 진입해 id 순서를 얻지만, is_deleted 는 인덱스가 답해 주지 못해
--   행마다 테이블을 들춰 확인해야 한다.
--   후보 B 는 is_deleted 를 두 번째 컬럼에 넣어 그 필터까지 인덱스 안에서 끝낸다.
--
--   대신 대가가 있다 — 컬럼이 하나 늘어 인덱스가 커지고, 쓰기 비용도 그만큼 늘어난다.
--   또 is_deleted 가 id 앞에 오므로 "is_deleted = false 로 고정한 뒤 id 내림차순"이라는
--   접근에서만 정렬 이득이 유지된다. 이 트레이드오프가 실제로 어느 쪽으로 기우는지는
--   추측이 아니라 측정으로 정한다.
--
--   M0 의 교훈이 정확히 이것이었다: 옵티마이저는 is_deleted 를 포함한 조건의 선택도를
--   filtered 5.00% 로 추정했지만(추정 770행), 실측은 14,963행이었다 — **19배 괴리**.
--   추정만 믿었다면 "필터가 이미 5%까지 줄여 주니 is_deleted 는 인덱스에 넣을 필요 없다"는
--   잘못된 결론에 도달했을 것이다. 그래서 A/B 를 둘 다 실제로 적용해 재는 것이다.
--
-- DROP INDEX 가 FK 제약을 깨지 않는 이유
--   V1 의 FK 제약 때문에 InnoDB 가 만든 author_id 단일 컬럼 인덱스 `fk_posts_author` 가
--   별도로 남아 있다(V2 를 적용해도 이 인덱스는 사라지지 않는다).
--   따라서 idx_posts_author_id_desc 를 지워도 fk_posts_author 가 FK 의 인덱스 요건을 계속 충족한다.
--   FK 를 지탱하는 유일한 인덱스를 지우려 했다면 MySQL 이 거부했을 것이다(ERROR 1553).
--
-- ※ 이 마이그레이션의 적용 순서
--   DROP 을 먼저 하고 CREATE 를 한다. 두 인덱스를 동시에 들고 있으면
--   옵티마이저가 어느 쪽을 골랐는지에 따라 측정이 오염되어 A/B 비교가 성립하지 않는다.
--
-- ※ 채택 확정 이후 (V4)
--   P1-13 의 실측 비교로 채택안이 정해지면, 그 결과에 맞춰 **V4 를 별도로 작성한다.**
--     · 후보 B 채택 → V4 는 현 상태를 확정하는 문서성 마이그레이션 또는 불필요
--     · 후보 A 채택 → V4 가 B 를 되돌리고 A 를 복원한다
--   어느 쪽이든 V2/V3 를 고쳐 쓰지 않는다 — 이미 적용된 마이그레이션을 수정하면
--   Flyway 체크섬이 깨질뿐더러, 비교의 기록 자체가 없어진다.
--   V4 의 작성과 snap-m1 생성은 측정 결과가 나온 뒤의 작업이다.
-- =====================================================================================

DROP INDEX idx_posts_author_id_desc ON posts;

CREATE INDEX idx_posts_author_deleted_id_desc ON posts (author_id, is_deleted, id DESC);
